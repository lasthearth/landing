/**
 * Запись адреса возврата после входа.
 */
export interface IReturnUrl {
    /**
     * Относительный адрес маршрута внутри сайта, например `/market?tab=kits`.
     */
    url: string;

    /**
     * Момент сохранения, мс с эпохи: по нему запись отсекается как устаревшая.
     */
    savedAt: number;
}
