/**
 * Полезная нагрузка `id_token`, выдаваемого Logto.
 * Содержит стандартные OIDC-claims и кастомные поля проекта.
 */
export interface IJwtTokenLh {
    /**
     * Идентификатор пользователя (стандартный claim `subject`).
     */
    sub: string;

    /**
     * Отображаемое имя пользователя.
     */
    name: string;

    /**
     * Логин пользователя в Logto.
     * Используется как основное имя в интерфейсе.
     */
    username?: string;

    /**
     * URL аватара пользователя.
     */
    picture?: string;

    /**
     * Время выпуска токена (Unix time, секунды).
     */
    iat: number;

    /**
     * Время истечения токена (Unix time, секунды).
     */
    exp?: number;

    /**
     * Роли пользователя в проекте.
     */
    roles?: string[];
}
