/**
 * Фильтр «был в игре» на странице игроков.
 *
 * Значения совпадают с query-параметрами адреса: адрес — источник истины
 * для страницы, поэтому отдельного перевода не требуется.
 */
export type LastSeenFilter = 'all' | 'online' | 'day' | 'week' | 'month' | 'inactive';

/**
 * Порядок сортировки списка игроков.
 */
export type PlayerSort = 'seen' | 'hours' | 'name';

/**
 * Запрос списка игроков: поиск, фильтр, сортировка и страница.
 *
 * Одна модель и для адреса страницы, и для запроса в API: так состояние
 * нельзя рассинхронизировать между ними.
 */
export interface PlayersQuery {
    /**
     * Поиск по нику (пусто — без поиска).
     */
    query: string;

    /**
     * Фильтр «был в игре».
     */
    lastSeen: LastSeenFilter;

    /**
     * Порядок сортировки.
     */
    sort: PlayerSort;

    /**
     * Номер страницы, начиная с единицы.
     */
    page: number;

    /**
     * Размер страницы.
     */
    pageSize: number;
}
