/**
 * Набор символов, допустимых в игровом нике (без якорей и квантификаторов).
 * Из него строятся и валидирующий паттерн, и regex для вырезания лишних
 * символов — одно правило в одном месте.
 */
const NICKNAME_CHARSET = 'A-Za-z0-9_-';

/**
 * Ограничения полей административной смены ника.
 */
export const NICKNAME_ADMIN_LIMITS = {
    /**
     * Допустимые символы и длина ника: `a-z A-Z 0-9 _ -`, 1–15 символов.
     */
    pattern: new RegExp(`^[${NICKNAME_CHARSET}]{1,15}$`),

    /**
     * Символы вне маски ника — для вырезания при вводе.
     */
    forbiddenChars: new RegExp(`[^${NICKNAME_CHARSET}]`, 'g'),

    /**
     * Максимальная длина ника.
     */
    nicknameMaxLength: 15,

    /**
     * Максимальная длина причины смены.
     */
    reasonMaxLength: 500,

    /**
     * Длительность кулдауна между сменами ника, месяцы.
     */
    cooldownMonths: 6,
} as const;
