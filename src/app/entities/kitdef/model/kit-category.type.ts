/**
 * Категория захваченного набора.
 *
 * Соответствует полю `category` схемы `kitdef.v1.KitDef`: значение пишет игра
 * при захвате набора и vsservice через `UpdateKit`. Поле, которое ни разу не
 * заполняли (или набор захвачен до его появления), сервер раскрывает в `"kit"`.
 *
 * Тот же набор значений использует товар донат-магазина
 * (`ShopCategory` в `@entities/donate`) — он читается из категории набора.
 */
export type KitCategory = 'kit' | 'privilege' | 'special';
