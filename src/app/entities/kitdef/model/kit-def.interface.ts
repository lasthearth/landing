import { KitCategory } from './kit-category.type';

/**
 * DTO позиции состава набора (`kitdef.v1.KitItem`).
 *
 * Поля отмечены необязательными там, где protobuf-JSON опускает нулевое
 * значение: маппер подставляет для них безопасный fallback.
 *
 * `attr_snapshot` в контракт не входит намеренно — снимок атрибутов
 * остаётся на сервере и на сайт не передаётся.
 */
export interface IKitItemDto {
    /**
     * Полный namespaced-код `Collectible.Code`.
     *
     * Однозначно определяет предмет или блок. Коды внутри одного набора
     * могут повторяться, поэтому позиция адресуется индексом, а не кодом.
     */
    game_code?: string;

    /**
     * Тип позиции: `"item"` (предмет) или `"block"` (блок).
     */
    type?: string;

    /**
     * Количество единиц в наборе.
     */
    quantity?: number;

    /**
     * URL иконки позиции в виде `<CDN>/<bucket>/<uuidv7>.png`.
     */
    image_url?: string;
}

/**
 * DTO захваченного набора (`kitdef.v1.KitDef`).
 *
 * Набор — это содержимое, которое пишет игра, плюс отображаемые метаданные
 * (`title`, `category`), которые пишет vsservice через `UpdateKit`.
 * Поля `code`, `items` и `created_at` принадлежат игре: PATCH их не меняет.
 */
export interface IKitDefDto {
    /**
     * Уникальный код набора, ключ upsert. Пишет игра.
     */
    code?: string;

    /**
     * Отображаемое название. Пишет `UpdateKit`.
     */
    title?: string;

    /**
     * Категория: `"kit"` (по умолчанию) | `"privilege"` | `"special"`.
     *
     * Незаполненное поле сервер раскрывает в `"kit"`.
     */
    category?: string;

    /**
     * Состав набора в том порядке, в котором его вернул `ListKits`.
     */
    items?: IKitItemDto[];

    /**
     * Дата захвата набора в формате ISO 8601.
     */
    created_at?: string;

    /**
     * Дата последнего изменения метаданных в формате ISO 8601.
     */
    updated_at?: string;
}

/**
 * UI-модель позиции состава набора.
 */
export interface IKitItem {
    /**
     * Полный namespaced-код `Collectible.Code`.
     */
    gameCode: string;

    /**
     * Тип позиции: `"item"` (предмет) или `"block"` (блок).
     */
    type: string;

    /**
     * Количество единиц в наборе.
     */
    quantity: number;

    /**
     * URL иконки позиции.
     */
    imageUrl: string;
}

/**
 * UI-модель захваченного набора.
 *
 * Индекс позиции в `items` совпадает с индексом, который принимает
 * `KitdefService.removeKitItem$`: порядок берётся из ответа `ListKits`.
 */
export interface IKitDef {
    /**
     * Уникальный код набора.
     */
    code: string;

    /**
     * Отображаемое название. Пустая строка, если название ещё не задали.
     */
    title: string;

    /**
     * Категория набора. Всегда одно из трёх значений, неизвестная или
     * пустая приводится к `'kit'`.
     */
    category: KitCategory;

    /**
     * Состав набора. Пустой массив, если позиций нет.
     */
    items: IKitItem[];

    /**
     * Дата захвата как объект Date.
     *
     * `null`, если сервер вернул невалидную или нулевую дату protobuf.
     */
    createdAt: Date | null;

    /**
     * Дата захвата в человекочитаемом формате.
     *
     * Формат: "DD.MM.YY - HH:mm" или "—", если дата отсутствует.
     */
    formattedCreatedAt: string;

    /**
     * Дата последнего изменения метаданных как объект Date.
     *
     * `null`, если сервер вернул невалидную или нулевую дату protobuf.
     */
    updatedAt: Date | null;

    /**
     * Дата изменения в человекочитаемом формате.
     *
     * Формат: "DD.MM.YY - HH:mm" или "—", если дата отсутствует.
     */
    formattedUpdatedAt: string;
}

/**
 * Запрос на обновление метаданных набора (`PATCH /v1/kitdefs/{code}`).
 *
 * Каждое поле необязательно: отсутствующее поле сервер оставляет без
 * изменения. Переданное `title` обязано быть непустым, переданная
 * `category` — одним из трёх известных значений, иначе сервер вернёт
 * 400 INVALID_ARGUMENT.
 *
 * Код набора в тело не кладётся: он приходит в пути запроса.
 */
export interface IUpdateKitRequest {
    /**
     * Новое отображаемое название. Не передавать, чтобы оставить прежнее.
     */
    title?: string;

    /**
     * Новая категория. Не передавать, чтобы оставить прежнюю.
     */
    category?: KitCategory;
}
