/**
 * Настройки баннера, привязанного к новости.
 *
 * Хранятся в скрытой метке внутри HTML новости (см. `appendNewsBanner`),
 * пока у бэкенда нет отдельного поля.
 */
export interface NewsBanner {
    /**
     * До какого момента показывать баннер (ISO 8601).
     */
    until: string;

    /**
     * Показывать обратный отсчёт до `until`.
     */
    countdown: boolean;
}
