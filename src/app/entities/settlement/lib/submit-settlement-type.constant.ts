/**
 * Тип заявки на надел — proto-перечисление `SubmitRequest.Type`
 * (`vsservice/proto/settlement/v1/settlement.proto`).
 *
 * Сервер принимает только `CAMP` и `GUILD`. Ноль — `TYPE_UNSPECIFIED`: с ним
 * `Submit` отвечает `INVALID_ARGUMENT` («invalid settlement type») до первого
 * чтения базы, поэтому заявка не создаётся и не повышается.
 *
 * Ступени (деревня, посёлок, город, провинция) заявка не несёт: `type` выбирает
 * только род группы — надел или гильдия. Повышение уровня сервер делает сам
 * (`SettlementVerification.LvlUp`), по текущей ступени одобренного надела, и
 * присланный тип перезаписывает своим. Поэтому все формы надела, включая формы
 * повышения, шлют `camp`.
 */
export const SUBMIT_SETTLEMENT_TYPE = {
    /** Основать надел или повысить его уровень. */
    camp: 1,

    /** Основать гильдию. */
    guild: 2,
} as const;
