/**
 * Где стоит блок-глашатай поселения — элемент ответа `GET /v1/settlements/notifiers`.
 *
 * Позицию пишет игровой сервер, когда глашатая ставят, и удаляет, когда его ломают;
 * у поселения не больше одного глашатая. Гильдий в списке нет. Запись переживает
 * удаление поселения, поэтому `settlement_id` может не найтись в списке поселений —
 * такие точки клиент отбрасывает.
 */
export interface INotifierPlacement {
    /**
     * Поселение, которому принадлежит глашатай. Пустая строка — глашатай не поселения,
     * а ключевой точки.
     */
    settlement_id: string;

    /**
     * Название с глашатая (у ключевой точки — единственное, что о ней известно).
     */
    name?: string;

    /**
     * Позиция блока в мире — абсолютные координаты, не от точки появления.
     * proto3 не присылает нулевые оси: 0 приходит как отсутствие поля.
     */
    position?: {
        x?: number;
        y?: number;
        z?: number;
    };
}
