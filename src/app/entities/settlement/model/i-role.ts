import { Permission } from './permission';

/**
 * Роль в поселении.
 * Набор прав, который owner может выдавать членам поселения.
 */
export interface IRole {
    /**
     * Идентификатор роли.
     * Служебная роль владельца имеет id `"owner"`.
     */
    id: string;

    /**
     * Отображаемое имя роли (1-64 символа, без `<`/`>`).
     * ВНИМАНИЕ (XSS): сервер хранит текст как есть, выводить только через интерполяцию `{{ }}`.
     */
    name: string;

    /**
     * Список прав, которые даёт роль.
     */
    permissions: Permission[];
}
