/**
 * Убирает из текста статьи разметку вики.
 *
 * Нужно для описания страницы: поисковику и превью ссылки нужен обычный
 * текст, а не `## Заголовок` и `[[адрес|подпись]]`.
 *
 * @param source Текст статьи в разметке вики.
 * @returns Текст без разметки, в одну строку.
 */
export function plainWikiText(source: string): string {
    return source
        .replace(/```[\s\S]*?```/g, ' ')
        .replace(/!\[[^\]]*\]\([^)]*\)/g, ' ')
        .replace(/\[\[([^\]|]+)\|([^\]]+)\]\]/g, '$2')
        .replace(/\[\[([^\]]+)\]\]/g, '$1')
        .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')
        .replace(/^\s*:::[^\n]*$/gm, ' ')
        .replace(/^\s*([-*_])\1{2,}\s*$/gm, ' ')
        .replace(/^\s{0,3}#{1,6}\s+/gm, '')
        .replace(/\*\*/g, '')
        .replace(/\s+/g, ' ')
        .trim();
}
