/**
 * Объявление для баннера над шапкой сайта.
 */
export interface Announcement {
    /**
     * Идентификатор новости, из которой взято объявление.
     */
    id: string;

    /**
     * Текст баннера — заголовок новости.
     */
    title: string;

    /**
     * До какого момента показывать (ISO 8601).
     */
    until: string;

    /**
     * Показывать обратный отсчёт до `until`.
     */
    countdown: boolean;
}
