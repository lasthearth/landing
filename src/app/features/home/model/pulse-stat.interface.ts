/**
 * Метрика блока «Пульс сервера» на главной.
 * Значение допускает `null`: карточка отрисовывается и до ответа сервера,
 * подставляя прочерк, иначе сетка прыгает при загрузке.
 */
export interface PulseStat {
    /**
     * Имя иконки Taiga UI.
     */
    readonly icon: string;

    /**
     * Ключ перевода подписи метрики.
     */
    readonly labelKey: string;

    /**
     * Значение метрики или `null`, если оно ещё не получено.
     */
    readonly value: string | number | null;
}
