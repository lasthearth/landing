/**
 * Ресурс, из которого складывается стоимость улучшения.
 *
 * `money` — деньги, количество в таллерах (серебряных). Курс сервера:
 * 1 дукат (золотая) = 100 серебряных, 1 серебряная = 10 медных; 1 серебряная = 1 БИ,
 * поэтому цены из схем владельца в БИ записываются как есть. На экране сумма
 * разложена на дукаты, серебряные и медные (`formatCost`).
 *
 * Материалы взяты из сборки сервера: доски, балки, срубы, гвозди, верёвки, стекло
 * и кирпич — из рецептов модов (`ballista`, `woodenfortifications`, `lhinsignia`),
 * камень и слитки — из ванильных блоков.
 *
 * Металл — только медь и ниже: слитков и гвоздей выше медных схемы не берут.
 * У материалов с породами (доски, балки, срубы, камень) в подписи стоит «любой породы».
 */
export type UpgradeResource =
    | 'money'
    | 'frames'
    | 'stone'
    | 'metal'
    | 'planks'
    | 'beams'
    | 'nails'
    | 'rope'
    | 'glass'
    | 'brick';
