/**
 * Ресурс, из которого складывается стоимость улучшения.
 *
 * `money` — деньги, количество в таллерах (серебряных). Курс сервера:
 * 1 дукат (золотая) = 100 серебряных, 1 серебряная = 100 медных; 1 серебряная = 1 БИ,
 * поэтому цены из схем владельца в БИ записываются как есть. На экране сумма
 * разложена на дукаты, серебряные и медные (`formatCost`).
 *
 * Материалы взяты из сборки сервера: доски, балки, срубы, гвозди, верёвки, стекло
 * и кирпич — из рецептов модов (`ballista`, `woodenfortifications`, `lhinsignia`),
 * камень и слитки — из ванильных блоков.
 *
 * Помимо стройматериалов схемы берут то, что нужно выковать, выплавить, вырастить
 * или найти: слитки оловянной и чёрной бронзы (плавка), древесный уголь и известь
 * (обжиг), смолу, кожу и льняное полотно (сбор и выделка), ржавые и темпоральные
 * шестерни (находки в руинах). Темпоральные шестерни — только на вершинах схем.
 *
 * Металл — не выше бронзы: железо даёт только прокачка шахты, а без железа нет и стали,
 * поэтому железо и сталь в ценах не участвуют. `metal` и `nails` по-прежнему медные.
 *
 * У материалов с породами (доски, балки, срубы, камень) в подписи стоит «любой породы».
 */
export type UpgradeResource =
    | 'money'
    | 'frames'
    | 'stone'
    | 'metal'
    | 'planks'
    | 'beams'
    | 'nails'
    | 'rope'
    | 'glass'
    | 'brick'
    | 'bronze'
    | 'blackBronze'
    | 'charcoal'
    | 'lime'
    | 'resin'
    | 'leather'
    | 'linen'
    | 'rustyGear'
    | 'temporalGear';
