/**
 * Состояние узла в планировщике.
 *
 * - `built` — отмечен построенным;
 * - `available` — все требования выполнены, можно строить;
 * - `locked` — не хватает предыдущих улучшений;
 * - `excluded` — в той же группе выбора уже выбрана другая специализация.
 */
export type UpgradeNodeState = 'built' | 'available' | 'locked' | 'excluded';
