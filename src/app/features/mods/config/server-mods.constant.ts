/**
 * Один мод игрового сервера в списке страницы «Моды сервера».
 */
export interface ServerMod {
    /** Название мода так, как его показывает лаунчер. */
    name: string;
    /** Версия мода, которую принимает сервер. */
    version: string;
    /** `true` — без мода игра не пустит на сервер. */
    required: boolean;
    /** Одна фраза о том, зачем мод нужен игроку. */
    description: string;
    /** Ссылка на страницу мода (пустая строка — ссылки не будет). */
    url: string;
}

/**
 * Моды игрового сервера: имя, версия, обязательность, описание и ссылка.
 *
 * Заполняет владелец: сейчас здесь один пример-заглушка. Чтобы добавить мод,
 * скопируйте блок целиком и замените значения:
 *
 * ```ts
 * {
 *     name: 'Имя мода',
 *     version: '1.0.0',
 *     required: true, // false — пометка «по желанию»
 *     description: 'Зачем мод нужен игроку, одной фразой.',
 *     url: 'https://example.com/mod', // '' — ссылки в строке не будет
 * },
 * ```
 *
 * Порядок строк в списке = порядок модов на странице. Пустой массив — страница
 * покажет заглушку «список модов ещё заполняется».
 */
export const SERVER_MODS: readonly ServerMod[] = [
    {
        name: '[ЗАПОЛНИТЬ] Пример мода',
        version: '1.0.0',
        required: true,
        description: '[ЗАПОЛНИТЬ] Одна фраза: зачем этот мод нужен игроку. Строку описания тоже пишет владелец.',
        url: '',
    },
];
