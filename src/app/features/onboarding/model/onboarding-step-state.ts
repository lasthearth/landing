/**
 * Состояние шага пути новичка.
 *
 * - `done` — сделано;
 * - `current` — следующий шаг, его и стоит сделать;
 * - `todo` — ещё впереди;
 * - `waiting` — сделано со стороны игрока, ждём решения (анкета на рассмотрении);
 * - `rejected` — анкету отклонили, нужно исправить.
 */
export type OnboardingStepState = 'done' | 'current' | 'todo' | 'waiting' | 'rejected';
