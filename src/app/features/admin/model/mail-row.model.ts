import { MailState } from '@entities/mail';

/**
 * Строка списка отправленных писем, подготовленная к показу.
 *
 * Считается один раз при загрузке страницы, а не в шаблоне: подписи состояния
 * и вложений зависят от даты и словаря, и вызов метода с аргументами на каждом
 * цикле обнаружения изменений превратил бы список из сотни писем в сотни
 * переводов на кадр.
 */
export interface MailRow {
    /**
     * Идентификатор письма.
     */
    id: string;

    /**
     * Ник получателя либо идентификатор, если ник не удалось получить.
     */
    recipient: string;

    /**
     * Письмо адресовано всем игрокам.
     */
    broadcast: boolean;

    /**
     * Заголовок письма.
     */
    title: string;

    /**
     * Текст письма.
     */
    body: string;

    /**
     * Время создания.
     */
    createdAt: Date | null;

    /**
     * Срок жизни; `null` — письмо бессрочное.
     */
    expiresAt: Date | null;

    /**
     * Состояние письма: действующее, истёкшее или отозванное.
     */
    state: MailState;

    /**
     * Ключ перевода подписи состояния.
     */
    stateKey: string;

    /**
     * Классы бейджа состояния.
     */
    stateClass: string;

    /**
     * Сколько игроков уже получили письмо (int64 строкой).
     */
    claimedCount: string;

    /**
     * Подписи вложений: «game:bread × 5», «3000 осколков».
     */
    attachmentTexts: string[];
}