/**
 * Данные диалога подтверждения принудительной смены ника игрока.
 */
export interface IConfirmNicknameChangeData {
    /**
     * Идентификатор игрока, которому меняют ник.
     */
    userId: string;

    /**
     * Новый ник: 1–15 символов, `a-z A-Z 0-9 _ -`.
     */
    newNickname: string;

    /**
     * Причина для уведомления игроку; отсутствует, если её не указали.
     */
    reason?: string;
}
