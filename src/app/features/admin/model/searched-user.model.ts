/**
 * Пользователь из выдачи `GET /users/search`.
 *
 * Минимальная форма для списка результатов поиска в админ-панелях:
 * остальное догружается через `GET /users/{user_id}`.
 */
export interface ISearchedUser {
    /**
     * Идентификатор пользователя.
     */
    user_id: string;

    /**
     * Игровое имя пользователя.
     */
    user_game_name: string;

    /**
     * Аватар: объект с несколькими размерами либо строка-URL.
     */
    avatar?: unknown;
}
