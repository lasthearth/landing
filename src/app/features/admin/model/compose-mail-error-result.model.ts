/**
 * Результат разбора ошибки отправки письма.
 */
export interface ComposeMailErrorResult {
    /**
     * Текст для уведомления и строки ошибки под формой.
     */
    text: string;

    /**
     * Сервер отказал в праве (`403`): форма показывает состояние «нет прав».
     */
    denied: boolean;
}