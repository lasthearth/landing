/**
 * Данные шага подтверждения отправки письма.
 *
 * Всё уже переведено и приведено к тексту: диалог показывает ровно то, что
 * уйдёт на сервер, и не пересчитывает формулировки сам.
 */
export interface IConfirmMailSendData {
    /**
     * Адресат: ник выбранного игрока либо «всем игрокам».
     */
    recipient: string;

    /**
     * Заголовок письма без пробелов по краям.
     */
    title: string;

    /**
     * Текст письма без пробелов по краям.
     */
    body: string;

    /**
     * Подписи вложений: «game:bread × 5», «3000 осколков».
     */
    attachments: string[];

    /**
     * Срок жизни письма либо текст «бессрочно».
     */
    expiresAt: string;
}