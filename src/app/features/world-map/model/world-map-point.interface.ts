/**
 * Тип поселения на карте.
 *
 * CAMP…PROVINCE — те же значения, что отдаёт API поселений. HAMLET — хутор:
 * на сайте его не регистрируют, но глашатая в игре ставят, поэтому на карте он есть.
 * KEY_POINT — ключевая точка: глашатай без поселения (`settlement_id` пустой).
 */
export type WorldMapSettlementType = 'HAMLET' | 'CAMP' | 'VILLAGE' | 'TOWNSHIP' | 'CITY' | 'PROVINCE' | 'KEY_POINT';

/**
 * Позиция блока-глашатая в мире.
 *
 * Координаты — как их показывает игра: от точки появления (Очага).
 * Ось X растёт на восток, ось Z — на юг, Y — высота.
 */
export interface WorldMapPosition {
    x: number;
    y: number;
    z: number;
}

/**
 * Поселение на карте земель.
 *
 * Точка на карте — не координаты из заявки, а место, где стоит блок-глашатай:
 * его ставят в игре, а сервер сам записывает позицию, поэтому она не может
 * разойтись с миром.
 */
export interface WorldMapPoint {
    /** Идентификатор точки на карте (глашатая). */
    id: string;
    /**
     * Поселение на сайте: по нему ведёт ссылка на страницу. У хутора его нет —
     * хутор живёт только в игре.
     */
    settlementId?: string;
    /** Название: у поселения — с сайта, у хутора — то, что написано на глашатае. */
    name: string;
    /** Тип поселения. */
    type: WorldMapSettlementType;
    /**
     * Курс в том виде, в каком его хранит API: «Миролюбивый», «Нейтральный»,
     * «Агрессивный». У хутора курса нет.
     */
    diplomacy?: string;
    /** Сколько жителей; у хутора сайт этого не знает. */
    membersCount?: number;
    /** Кто поставил глашатая — для хутора это и есть хозяин. */
    placedBy?: string;
    /** Где стоит блок-глашатай. */
    herald: WorldMapPosition;
}

/**
 * Данные для карты.
 */
export interface WorldMapData {
    /** Поселения с поставленным глашатаем. */
    points: WorldMapPoint[];
    /**
     * Пример вместо настоящих данных: бэкенд ещё не отдаёт позиции глашатаев
     * списком. Страница честно предупреждает об этом и не ведёт на страницы
     * несуществующих поселений.
     */
    demo: boolean;
}
