/**
 * Одна снежинка снегопада: положение, размер и параметры падения.
 */
export interface ISnowflake {
    /**
     * Положение по X в CSS-пикселях.
     */
    x: number;

    /**
     * Положение по Y в CSS-пикселях.
     */
    y: number;

    /**
     * Радиус в CSS-пикселях.
     */
    radius: number;

    /**
     * Скорость падения в пикселях за секунду.
     */
    speed: number;

    /**
     * Размах покачивания по горизонтали в пикселях.
     */
    sway: number;

    /**
     * Фаза покачивания в радианах.
     */
    phase: number;

    /**
     * Непрозрачность от 0 до 1.
     */
    alpha: number;
}
