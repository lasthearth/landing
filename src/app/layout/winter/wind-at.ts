/**
 * Сила ветра в момент времени: сумма медленных синусоид без общего периода,
 * поэтому порывы не повторяются заметным ритмом. Функция чистая, и оба плана
 * снегопада получают один и тот же ветер без общего состояния.
 *
 * @param seconds Время в секундах.
 * @returns Сила ветра от -1 (влево) до 1 (вправо).
 */
export function windAt(seconds: number): number {
    return 0.55 * Math.sin(seconds * 0.11) + 0.3 * Math.sin(seconds * 0.037 + 2) + 0.15 * Math.sin(seconds * 0.29 + 1);
}
