/**
 * Превращает текст в разметке редактора в простой текст одной строкой.
 *
 * Нужен там, где разметка не помещается: превью в карточке с обрезкой
 * по строкам, подсказки, файлы календаря. Спойлеры не раскрываются —
 * вместо них многоточие. Картинки выпадают, у ссылок остаётся текст.
 *
 * @param source Исходный текст из редактора.
 * @returns Простой текст без переводов строк.
 */
export function newsMarkdownToPlain(source: string): string {
    return source
        .replace(/\r\n?/g, '\n')
        .replace(/^!\[[^\]]*\]\([^)]*\)\s*$/gm, '')
        .replace(/\|\|[\s\S]*?\|\|/g, '…')
        .replace(/\[([^\]]+)\]\([^)]+\)/g, '$1')
        .replace(/^\s*#{1,3}\s+/gm, '')
        .replace(/^\s*>\s?/gm, '')
        .replace(/^\s*(?:[-*•]|\d+[.)])\s+/gm, '')
        .replace(/^\s*-{3,}\s*$/gm, '')
        .replace(/(\*\*|__|~~|`)/g, '')
        .replace(/(^|[^*\w])\*(\S[^*]*?)\*(?!\w)/g, '$1$2')
        .replace(/\s+/g, ' ')
        .trim();
}
