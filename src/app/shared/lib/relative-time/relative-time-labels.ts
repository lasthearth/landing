/**
 * Подписи, которых нет в `Intl.RelativeTimeFormat`.
 *
 * Передаются из i18n, чтобы функция форматирования оставалась чистой
 * и не зависела от сервиса переводов.
 */
export interface RelativeTimeLabels {
    /**
     * Меньше минуты назад: «только что».
     */
    justNow: string;

    /**
     * Ровно одна минута: «минуту назад» вместо «1 минуту назад».
     */
    minuteAgo: string;

    /**
     * Ровно один час: «час назад» вместо «1 час назад».
     */
    hourAgo: string;

    /**
     * От 7 до 13 дней назад: «неделю назад».
     */
    weekAgo: string;
}
