/**
 * Настройки сжатия изображения.
 */
export interface CompressImageOptions {
    /**
     * Максимальная ширина результирующего изображения.
     * @default 1920
     */
    maxWidth?: number;

    /**
     * Максимальная высота результирующего изображения.
     * @default 1920
     */
    maxHeight?: number;

    /**
     * Качество сжатия для lossy-форматов (0..1).
     * @default 0.92
     */
    quality?: number;

    /**
     * Целевой MIME-тип (например, "image/webp").
     * @default "image/webp"
     */
    mimeType?: string;

    /**
     * Максимальный размер результата в байтах.
     *
     * Если задан, кадр перекодируется со всё более низким качеством, а затем
     * и в меньшем размере, пока результат не уложится в лимит или не кончатся
     * попытки. Без него кодирование выполняется один раз с указанным качеством.
     *
     * Лимит не гарантирован: шумный кадр может не уложиться даже на минимальном
     * качестве и минимальном размере — тогда возвращается наименьший из
     * полученных вариантов, а решение о непригодности файла принимает вызывающий
     * код (валидатор формы).
     */
    maxSizeBytes?: number;
}
