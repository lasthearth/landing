/**
 * Картинка для полноэкранного просмотрщика.
 */
export interface ImageViewerItem {
    /**
     * Адрес картинки, которую показывает просмотрщик.
     */
    src: string;

    /**
     * Адрес настоящего оригинала для ссылки «открыть в новой вкладке».
     *
     * Нужен, когда `src` — уменьшенная копия: просмотрщик показывает
     * лёгкую картинку, а уводит посетителя на полную. Без поля ссылка
     * открыла бы ту же копию.
     */
    originalSrc?: string;

    /**
     * Альтернативный текст.
     */
    alt: string;

    /**
     * Подпись (автор, описание).
     */
    caption?: string;

    /**
     * Слова автора картинки, если он их написал.
     *
     * Выводится второй строкой под подписью. Отдельное поле, а не часть
     * `caption`: подпись короткая и всегда есть, а текст автора бывает
     * длинным и встречается не у каждой картинки.
     */
    note?: string;

    /**
     * Дата публикации — выводится относительным временем.
     */
    date?: string | Date | null;

    /**
     * Ссылка на эту картинку для кнопки «Поделиться».
     */
    shareUrl?: string;
}
